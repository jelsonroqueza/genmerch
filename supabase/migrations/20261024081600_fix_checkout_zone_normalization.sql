CREATE OR REPLACE FUNCTION genmerch_private.zone_for_province(p_province text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $function$
DECLARE
  v text := regexp_replace(upper(btrim(coalesce(p_province, ''))), '[^A-Z0-9]', '', 'g');
BEGIN
  v := regexp_replace(v, '^(PROVINCEOF|PROVINCIALGOVERNMENTOF)', '');
  IF v = ANY (ARRAY[
    'NCR','METROMANILA','NATIONALCAPITALREGION','MANILA',
    'ABRA','APAYAO','BENGUET','IFUGAO','KALINGA','MOUNTAINPROVINCE',
    'ILOCOSNORTE','ILOCOSSUR','LAUNION','PANGASINAN',
    'BATANES','CAGAYAN','ISABELA','NUEVAVIZCAYA','QUIRINO',
    'AURORA','BATAAN','BULACAN','NUEVAEJIJA','PAMPANGA','TARLAC','ZAMBALES',
    'BATANGAS','CAVITE','LAGUNA','QUEZON','RIZAL',
    'OCCIDENTALMINDORO','ORIENTALMINDORO','MARINDUQUE','ROMBLON','PALAWAN',
    'ALBAY','CAMARINESNORTE','CAMARINESSUR','CATANDUANES','MASBATE','SORSOGON'
  ]) THEN
    RETURN 'Luzon';
  ELSIF v = ANY (ARRAY[
    'AKLAN','ANTIQUE','CAPIZ','GUIMARAS','ILOILO','NEGROSOCCIDENTAL',
    'BOHOL','CEBU','NEGROSORIENTAL','SIQUIJOR',
    'BILIRAN','EASTERNSAMAR','LEYTE','NORTHERNSAMAR','SAMAR','WESTERNSAMAR','SOUTHERNLEYTE'
  ]) THEN
    RETURN 'Visayas';
  ELSIF v = ANY (ARRAY[
    'ZAMBOANGADELNORTE','ZAMBOANGADELSUR','ZAMBOANGASIBUGAY',
    'BUKIDNON','CAMIGUIN','LANAODELNORTE','MISAMISOCCIDENTAL','MISAMISORIENTAL',
    'DAVAO DE ORO','DAVAO DEORO','DAVAOORIENTAL','DAVAODELNORTE','DAVAODELSUR','DAVAOCCIDENTAL',
    'COTABATO','NORTHCOTABATO','SARANGANI','SOUTHCOTABATO','SULTANKUDARAT',
    'AGUSANDELNORTE','AGUSANDELSUR','DINAGATISLANDS','SURIGAODELNORTE','SURIGAODELSUR',
    'BASILAN','LANAODELSUR','MAGUINDANAODELNORTE','MAGUINDANAODELSUR','SULU','TAWITAWI',
    'COMPOSTELLAVALLEY'
  ]) THEN
    RETURN 'Mindanao';
  END IF;
  RETURN NULL;
END;
$function$;
REVOKE ALL ON FUNCTION genmerch_private.zone_for_province(text) FROM PUBLIC, anon, authenticated;
